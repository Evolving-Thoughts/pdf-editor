import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { PDFDocument } from 'pdf-lib'
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH ?? execFileSync('which', ['chromium'], { encoding: 'utf8' }).trim(), args: ['--no-sandbox'] })
const context = await browser.newContext({ viewport: { width: 1280, height: 900 } })
const page = await context.newPage()
const errors = []
page.on('pageerror', e => errors.push(String(e)))
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
const artifactDir = process.env.SMOKE_ARTIFACT_DIR ?? mkdtempSync(join(tmpdir(), 'pdf-editor-t4-'))
mkdirSync(artifactDir, { recursive: true })
const baseUrl = process.env.SMOKE_URL ?? 'http://localhost:5199'
try {
  await page.goto(baseUrl)
  await page.locator('input[type=file][accept="application/pdf"]').setInputFiles(new URL('../tests/fixtures/zweiseitig.pdf', import.meta.url).pathname)
  await page.waitForSelector('.page canvas')
  const pen = page.getByRole('button', { name: 'Stift', exact: true })
  assert.equal(await pen.count(), 1, 'Freihand-Werkzeug ist erreichbar')
  await pen.click()
  const sheet = await page.locator('.page').first().boundingBox()
  await page.mouse.move(sheet.x + 100, sheet.y + 300)
  await page.mouse.down()
  await page.mouse.move(sheet.x + 300, sheet.y + 300, { steps: 20 })
  await page.mouse.up()
  assert.equal(await page.locator('.stroke').count(), 1, 'Ein Stiftzug wird als Strich sichtbar')
  await page.getByRole('button', { name: 'Rückgängig', exact: true }).click()
  assert.equal(await page.locator('.stroke').count(), 0, 'Undo entfernt den ganzen Stiftzug')
  const bar = page.getByRole('group', { name: 'Zeichenoptionen' })
  assert.equal(await bar.count(), 1, 'Zeichenoptionen sind als Kontextleiste erreichbar')
  const initial = await bar.boundingBox()
  const grip = page.getByRole('button', { name: 'Kontextleiste verschieben' })
  const handle = await grip.boundingBox()
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2)
  await page.mouse.down()
  await page.mouse.move(handle.x + handle.width / 2 + 160, handle.y + handle.height / 2 + 120, { steps: 10 })
  await page.mouse.up()
  const moved = await bar.boundingBox()
  assert.ok(moved.x > initial.x + 100 && moved.y > initial.y + 80, 'Leiste lässt sich am Griff verschieben')
  await page.getByRole('button', { name: 'Blau', exact: true }).click()
  assert.deepEqual(await bar.boundingBox(), moved, 'Farbwahl verschiebt die Leiste nicht')
  await page.getByRole('button', { name: 'Auswahl', exact: false }).click()
  assert.equal(await bar.isVisible(), false, 'Leiste nur beim Zeichnen sichtbar')
  await pen.click()
  assert.deepEqual(await bar.boundingBox(), moved, 'Position bleibt beim Werkzeugwechsel erhalten')
  await grip.focus()
  await page.keyboard.press('ArrowRight')
  const keyboardMoved = await bar.boundingBox()
  assert.equal(Math.round(keyboardMoved.x - moved.x), 10, 'Griff ist per Tastatur verschiebbar')
  await page.getByRole('button', { name: 'Position zurücksetzen' }).click()
  assert.deepEqual(await bar.boundingBox(), initial, 'Reset stellt Ausgangsposition wieder her')
  console.log('PASS Kontextleiste: Drag, Farbwahl, Werkzeugwechsel, Tastatur und Reset')
  await page.getByRole('button', { name: 'Wiederholen', exact: true }).click()
  await page.getByRole('button', { name: '6 pt Strichstärke', exact: true }).click()
  await page.mouse.move(sheet.x + 100, sheet.y + 400)
  await page.mouse.down()
  await page.mouse.move(sheet.x + 300, sheet.y + 400, { steps: 20 })
  await page.mouse.up()
  assert.equal(await page.locator('.stroke').count(), 2)
  assert.equal(await page.locator('.stroke').nth(1).getAttribute('stroke'), '#2455c7')
  assert.equal(await page.locator('.stroke').nth(1).getAttribute('stroke-width'), '6')
  await page.getByRole('button', { name: 'Radierer', exact: true }).click()
  await page.mouse.move(sheet.x + 200, sheet.y + 285)
  await page.mouse.down()
  await page.mouse.move(sheet.x + 200, sheet.y + 315, { steps: 10 })
  await page.mouse.up()
  assert.equal(await page.locator('.stroke').count(), 3, 'Radierer splittet nur den berührten Strich')
  const erasedPaths = await page.locator('.stroke').evaluateAll(paths => paths.map(p => p.getAttribute('d')))
  await page.getByRole('button', { name: 'Rückgängig', exact: true }).click()
  assert.equal(await page.locator('.stroke').count(), 2, 'Ein Undo macht die ganze Radiergeste rückgängig')
  await page.getByRole('button', { name: 'Wiederholen', exact: true }).click()
  assert.deepEqual(await page.locator('.stroke').evaluateAll(paths => paths.map(p => p.getAttribute('d'))), erasedPaths)
  await page.mouse.click(sheet.x + 500, sheet.y + 500)
  assert.deepEqual(await page.locator('.stroke').evaluateAll(paths => paths.map(p => p.getAttribute('d'))), erasedPaths, 'Radierer-Miss verändert nichts')
  console.log('PASS Farben, Stärke, Teilradierung und Undo/Redo')

  await pen.click()
  const beforeBound = await grip.boundingBox()
  await page.mouse.move(beforeBound.x + 20, beforeBound.y + 20)
  await page.mouse.down()
  await page.mouse.move(2000, 2000, { steps: 10 })
  await page.mouse.up()
  const workspace = await page.locator('.workspace').boundingBox()
  const atEdge = await bar.boundingBox()
  assert.ok(atEdge.x >= workspace.x && atEdge.y >= workspace.y &&
    atEdge.x + atEdge.width <= workspace.x + workspace.width && atEdge.y + atEdge.height <= workspace.y + workspace.height,
    'Leiste bleibt auch nach extremer Verschiebung im Arbeitsbereich')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.waitForTimeout(100)
  const smallWork = await page.locator('.workspace').boundingBox()
  const smallBar = await bar.boundingBox()
  assert.ok(smallBar.x + smallBar.width <= smallWork.x + smallWork.width, 'Viewport-Schrumpfen hält den Griff erreichbar')
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Kein horizontales Seiten-Overflow')
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.getByRole('button', { name: 'Position zurücksetzen' }).click()
  await page.getByRole('button', { name: '+', exact: true }).click()
  await page.getByRole('button', { name: '+', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.zoom-label')?.textContent?.includes('150'))
  await page.locator('.pages').evaluate(container => {
    container.scrollTop = container.querySelectorAll('.page')[1].offsetTop - 16
  })
  const secondSheet = await page.locator('.page').nth(1).boundingBox()
  await page.mouse.move(secondSheet.x + 90, secondSheet.y + 210)
  await page.mouse.down()
  await page.mouse.move(secondSheet.x + 240, secondSheet.y + 210)
  await page.mouse.up()
  assert.equal(await page.locator('.page').nth(1).locator('.stroke').getAttribute('d'), 'M 60 140 L 160 140', 'Zoom und zweite Seite verwenden PDF-Punkte')
  await page.getByRole('button', { name: 'Rückgängig', exact: true }).click()
  await page.getByRole('button', { name: '−', exact: true }).click()
  await page.getByRole('button', { name: '−', exact: true }).click()
  await page.locator('.pages').evaluate(container => { container.scrollTop = 0 })
  console.log('PASS Zoom und zweite Seite')
  await page.waitForTimeout(750)
  await page.reload()
  await page.getByRole('button', { name: /Entwürfe/ }).click()
  await page.locator('.draft-open').first().click()
  await page.waitForSelector('.stroke', { state: 'attached' })
  assert.deepEqual(await page.locator('.stroke').evaluateAll(paths => paths.map(p => p.getAttribute('d'))), erasedPaths, 'Striche und Teilradierung überleben Reload')
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportieren', exact: true }).click()
  const download = await downloadEvent
  await download.saveAs(join(artifactDir, 'drawing-export.pdf'))
  assert.equal((await PDFDocument.load(readFileSync(join(artifactDir, 'drawing-export.pdf')))).getPageCount(), 2)
  await pen.click()
  await page.screenshot({ path: join(artifactDir, 'desktop.png') })
  await page.getByRole('button', { name: 'Radierer', exact: true }).click()
  await page.screenshot({ path: join(artifactDir, 'eraser.png') })
  await pen.click()
  console.log('PASS Begrenzung, kleiner Viewport, Auto-Save, Reload und Export')

  const touchContext = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })
  const touchPage = await touchContext.newPage()
  touchPage.on('pageerror', e => errors.push(String(e)))
  await touchPage.goto(baseUrl)
  await touchPage.locator('input[type=file][accept="application/pdf"]').setInputFiles(new URL('../tests/fixtures/zweiseitig.pdf', import.meta.url).pathname)
  await touchPage.waitForSelector('.page canvas')
  await touchPage.getByRole('button', { name: 'Stift', exact: true }).tap()
  const touchSheet = await touchPage.locator('.page').first().boundingBox()
  const cdp = await touchContext.newCDPSession(touchPage)
  const touch = async (type, x, y) => {
    await cdp.send('Input.dispatchTouchEvent', {
      type, touchPoints: type === 'touchEnd' || type === 'touchCancel' ? [] : [{ x, y, id: 1, radiusX: 1, radiusY: 1, force: 1 }],
    })
    // Give Chromium's touch gesture recognizer a realistic sample interval.
    // Back-to-back protocol events can suppress the next compatibility click.
    await touchPage.waitForTimeout(100)
  }
  await touch('touchStart', touchSheet.x + 100, touchSheet.y + 200)
  await touch('touchMove', touchSheet.x + 200, touchSheet.y + 230)
  await touch('touchEnd')
  assert.equal(await touchPage.locator('.stroke').count(), 1, 'Echte Touch-Eingabe zeichnet')
  await touch('touchStart', touchSheet.x + 100, touchSheet.y + 280)
  await touch('touchMove', touchSheet.x + 200, touchSheet.y + 290)
  await touch('touchCancel')
  assert.equal(await touchPage.locator('.stroke').count(), 1, 'Abgebrochene Touch-Geste bleibt nicht im Dokument')
  const touchBar = touchPage.getByRole('group', { name: 'Zeichenoptionen' })
  const touchGrip = await touchPage.getByRole('button', { name: 'Kontextleiste verschieben' }).boundingBox()
  const touchOriginal = await touchBar.boundingBox()
  await touch('touchStart', touchGrip.x + 20, touchGrip.y + 20)
  await touch('touchMove', touchGrip.x + 20, touchGrip.y + 100)
  await touch('touchEnd')
  assert.ok((await touchBar.boundingBox()).y > touchOriginal.y + 60, 'Touch verschiebt die Leiste nur am Griff')
  await touchPage.getByRole('button', { name: 'Position zurücksetzen' }).tap()
  await touchPage.waitForFunction(() => document.querySelector('.drawing-toolbar')?.style.top === '16px')
  await touchPage.getByRole('button', { name: 'Zeichnung löschen', exact: true }).tap()
  assert.equal(await touchPage.locator('.stroke').count(), 0, 'Löschen funktioniert per Touch')
  await touchPage.getByRole('button', { name: 'Rückgängig', exact: true }).tap()
  assert.equal(await touchPage.locator('.stroke').count(), 1, 'Touch-Undo stellt die Zeichnung wieder her')
  const touchPath = await touchPage.locator('.stroke').getAttribute('d')
  await touchPage.getByRole('button', { name: 'Radierer', exact: true }).tap()
  await touchPage.getByRole('button', { name: '48 pt Radierergröße', exact: true }).tap()
  assert.equal(await touchPage.getByRole('button', { name: '48 pt Radierergröße', exact: true }).getAttribute('aria-pressed'), 'true')
  await touch('touchStart', touchSheet.x + 150, touchSheet.y + 215)
  assert.equal(await touchPage.locator('.stroke-preview').getAttribute('stroke-width'), '48')
  await touch('touchEnd')
  assert.equal(await touchPage.locator('.stroke').count(), 2, 'Gewählte Touch-Radierergröße schneidet den Strich')
  await touchPage.getByRole('button', { name: 'Rückgängig', exact: true }).tap()
  assert.equal(await touchPage.locator('.stroke').getAttribute('d'), touchPath)
  await touchPage.getByRole('button', { name: 'Stift', exact: true }).tap()
  await touchPage.screenshot({ path: join(artifactDir, 'mobile.png') })
  await touchContext.close()
  assert.deepEqual(errors, [], 'Keine Laufzeitfehler')
  console.log('PASS Touch-Zeichnen, Touch-Abbruch, Touch-Griff, Radierergrößen und Löschen mit Undo')
  console.log('PASS Stiftzug und Undo')
} finally {
  await browser.close()
}
